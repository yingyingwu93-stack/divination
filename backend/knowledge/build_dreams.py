def build():
    items = []
    seen = set()
    for index, (title, category, keywords, traditional, psychology) in enumerate(DREAMS, 1):
        if title in seen:
            continue
        seen.add(title)
        items.append({
            "id": f"dream-{index:03d}",
            "title": title,
            "category": category,
            "keywords": [k.strip() for k in keywords.split(",") if k.strip()],
            "traditional": traditional,
            "psychology": psychology,
        })

    if len(items) < 300:
        raise SystemExit(f"词条数量不足：{len(items)} < 300")

    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "dreams.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=1)

    categories = {}
    for item in items:
        categories[item["category"]] = categories.get(item["category"], 0) + 1
    print(f"已生成 {len(items)} 条梦境词条 -> {out_path}")
    print("分类统计：", categories)


if __name__ == "__main__":
    build()
